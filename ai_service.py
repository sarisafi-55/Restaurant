import os
import json
import time


MODEL_DEFAULT = "gemini-3.6-flash"


# =========================================================
# GEMINI CLIENT
# =========================================================

def _client():

    key = os.getenv("GEMINI_API_KEY", "").strip()

    if not key:
        return None

    from google import genai

    return genai.Client(
        api_key=key
    )


# =========================================================
# CONVERT DATAFRAME TO RECORDS
# =========================================================

def _records(frame, limit):

    if frame is None or frame.empty:
        return []

    return (
        frame
        .head(limit)
        .to_dict("records")
    )


# =========================================================
# PREPARE DATA FOR AI
# =========================================================

def _context(stats, df=None):

    out = {

        "total_sales": round(
            stats["total_sales"],
            2
        ),

        "total_qty": stats["total_qty"],

        "orders": stats["orders"],

        "avg_order_value": round(
            stats["avg_order_value"],
            2
        ),

        "best_menu": stats["best_menu"],

        "peak_hour": stats["peak_hour"],

        "menu_sales": _records(
            stats["menu_sales"],
            50
        ),

        "hourly_sales": _records(
            stats["hourly"].sort_values("Hour"),
            24
        ),

        "period_sales": _records(
            stats["period"],
            10
        ),

        "category_sales": _records(
            stats["category"],
            30
        ),

        "daily_sales": _records(
            stats["daily"],
            90
        ),
    }


    # -----------------------------------------------------
    # เพิ่มข้อมูลราคาของแต่ละเมนู
    # เพื่อให้ AI คิดโปรโมชั่นได้
    # -----------------------------------------------------

    if df is not None:

        out["row_count"] = len(df)

        out["columns"] = list(
            df.columns
        )


        if (
            "Menu" in df.columns
            and "Price" in df.columns
        ):

            menu_prices = (

                df.groupby(
                    "Menu",
                    as_index=False
                )

                .agg(
                    Price=("Price", "median")
                )

                .sort_values(
                    "Menu"
                )
            )

            out["menu_prices"] = _records(
                menu_prices,
                100
            )


        # -------------------------------------------------
        # ยอดขายเมนูแยกตามช่วงเวลา
        # ใช้หาเวลาที่เหมาะกับโปรโมชั่น
        # -------------------------------------------------

        if all(
            col in df.columns
            for col in [
                "Menu",
                "Period",
                "Sales"
            ]
        ):

            menu_period = (

                df.groupby(
                    [
                        "Menu",
                        "Period"
                    ],
                    observed=True,
                    as_index=False
                )

                .agg(
                    Sales=("Sales", "sum"),
                    Quantity=("Quantity", "sum")
                )
            )

            out["menu_period_sales"] = _records(
                menu_period,
                200
            )


    return out


# =========================================================
# CALL GEMINI
# =========================================================

def _generate(prompt):

    client = _client()


    if not client:

        return (
            "ยังไม่ได้ตั้งค่า GEMINI_API_KEY "
            "จึงยังใช้ AI ไม่ได้"
        )


    model = (
        os.getenv(
            "GEMINI_MODEL",
            MODEL_DEFAULT
        ).strip()
        or MODEL_DEFAULT
    )


    last_error = None


    for attempt in range(3):

        try:

            r = client.models.generate_content(
                model=model,
                contents=prompt
            )


            text = getattr(
                r,
                "text",
                None
            )


            if text:

                return text.strip()


            return (
                "AI ไม่ได้ส่งข้อความตอบกลับ "
                "กรุณาลองใหม่"
            )


        except Exception as e:

            last_error = e

            msg = str(e)


            if (
                "503" in msg
                or "UNAVAILABLE" in msg
                or "high demand" in msg.lower()
            ):

                time.sleep(
                    2 + attempt * 2
                )

                continue


            break


    if (
        last_error
        and (
            "503" in str(last_error)
            or
            "UNAVAILABLE" in str(last_error)
        )
    ):

        return (
            "ขณะนี้บริการ AI "
            "มีผู้ใช้งานจำนวนมาก "
            "ระบบลองเชื่อมต่อให้อัตโนมัติแล้ว "
            "กรุณารอสักครู่และลองใหม่"
        )


    return (
        f"AI ยังไม่สามารถตอบได้: "
        f"{last_error}"
    )


